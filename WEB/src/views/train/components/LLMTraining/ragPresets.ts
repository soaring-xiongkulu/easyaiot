/** 去掉 Markdown 符号后的单行预览文本，避免 ##、**、列表符等噪音出现在列表里 */
export function previewContent(text: string | undefined, max = 64) {
  return (text || '')
    .replace(/```[\s\S]*?(```|$)/g, ' ')
    .replace(/`([^`]*)`/g, '$1')
    .replace(/^#{1,6}\s*/gm, '')
    .replace(/\*\*([^*]*)\*\*/g, '$1')
    .replace(/^\s*[-*+]\s+/gm, '')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, max);
}
